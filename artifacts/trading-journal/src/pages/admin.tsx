function SetupTypeReassignPanel({ users }: { users: AdminUser[] }) {
  const queryClient = useQueryClient();
  const [selectedUserId, setSelectedUserId] = useState<number | "">("");
  const [selectedTradeId, setSelectedTradeId] = useState<number | "">("");
  const [selectedNewSetupTypeId, setSelectedNewSetupTypeId] = useState<string>("null");
  const [success, setSuccess] = useState(false);
  const [error, setError] = useState<string | null>(null);

  const userId = selectedUserId !== "" ? selectedUserId : null;

  const tradesQuery = useQuery({
    queryKey: ["admin-user-trades", userId],
    queryFn: () => listAdminUserTrades(userId!),
    enabled: userId !== null,
  });

  const setupTypesQuery = useQuery({
    queryKey: ["admin-user-setup-types", userId],
    queryFn: () => listAdminUserSetupTypes(userId!),
    enabled: userId !== null,
  });

  const reassignMutation = useMutation({
    mutationFn: ({ tradeId, newSetupTypeId }: { tradeId: number; newSetupTypeId: number | null }) =>
      adminUpdateTradeSetupType(tradeId, newSetupTypeId),
    onSuccess: () => {
      setError(null);
      setSuccess(true);
      setSelectedTradeId("");
      setSelectedNewSetupTypeId("null");
      queryClient.invalidateQueries({ queryKey: ADMIN_SETUP_TYPE_CHANGE_LOG_KEY });
      // Also invalidate trades cache so the same user's list reflects the new assignment
      queryClient.invalidateQueries({ queryKey: ["admin-user-trades", userId] });
      setTimeout(() => setSuccess(false), 3000);
    },
    onError: (err) => {
      setSuccess(false);
      setError(err instanceof Error ? err.message : "Failed to update setup type.");
    },
  });

  function handleUserChange(value: string) {
    setSelectedUserId(value === "" ? "" : Number(value));
    setSelectedTradeId("");
    setSelectedNewSetupTypeId("null");
    setError(null);
    setSuccess(false);
  }

  function handleReassign() {
    if (selectedTradeId === "") return;
    const newSetupTypeId = selectedNewSetupTypeId === "null" ? null : Number(selectedNewSetupTypeId);
    reassignMutation.mutate({ tradeId: selectedTradeId as number, newSetupTypeId });
  }

  const selectClass =
    "w-full rounded-lg border border-border/60 bg-background/60 px-4 py-2.5 text-sm focus:outline-none focus:ring-2 focus:ring-primary/50 focus:border-primary/50 transition disabled:opacity-50";

  return (
    <div className="rounded-2xl border border-border/50 bg-card/60 backdrop-blur-xl p-6 shadow-2xl mt-4">
      <div className="flex items-center gap-2 mb-5">
        <Tag className="w-4 h-4 text-muted-foreground" />
        <h2 className="text-base font-semibold tracking-tight">Reassign setup type</h2>
        <span className="text-xs text-muted-foreground ml-auto">admin only</span>
      </div>

      <div className="space-y-3">
        {/* Step 1: pick a user */}
        <select value={selectedUserId} onChange={(e) => handleUserChange(e.target.value)} className={selectClass}>
          <option value="">— Select a user —</option>
          {users.map((u) => (
            <option key={u.id} value={u.id}>
              User {u.id} ({u.tradeCount} {u.tradeCount === 1 ? "trade" : "trades"})
            </option>
          ))}
        </select>

        {/* Step 2: pick a trade (visible once a user is selected) */}
        {userId !== null && (
          <>
            {tradesQuery.isLoading && (
              <p className="text-sm text-muted-foreground">Loading trades…</p>
            )}
            {tradesQuery.isError && (
              <p className="text-sm text-destructive">Failed to load trades.</p>
            )}
            {tradesQuery.data && tradesQuery.data.length === 0 && (
              <p className="text-sm text-muted-foreground">No trades for this user.</p>
            )}

            {tradesQuery.data && tradesQuery.data.length > 0 && (
              <>
                <select
                  value={selectedTradeId}
                  onChange={(e) => {
                    setSelectedTradeId(e.target.value === "" ? "" : Number(e.target.value));
                    setError(null);
                    setSuccess(false);
                  }}
                  className={selectClass}
                >
                  <option value="">— Select a trade —</option>
                  {tradesQuery.data.map((t: AdminTrade) => (
                    <option key={t.id} value={t.id}>
                      {t.weekLabel} · T{t.tradeNumber} · {t.result}
                      {t.archivedAt ? " [archived]" : ""}
                      {t.setupTypeName ? ` · ${t.setupTypeName}` : ""}
                    </option>
                  ))}
                </select>

                {/* Step 3: pick the new setup type */}
                <select
                  value={selectedNewSetupTypeId}
                  onChange={(e) => {
                    setSelectedNewSetupTypeId(e.target.value);
                    setError(null);
                    setSuccess(false);
                  }}
                  className={selectClass}
                  disabled={setupTypesQuery.isLoading}
                >
                  <option value="null">— Clear (no setup type) —</option>
                  {setupTypesQuery.data?.map((st) => (
                    <option key={st.id} value={st.id}>
                      {st.name}{!st.active ? " (inactive)" : ""}
                    </option>
                  ))}
                </select>

                {error && (
                  <div className="flex items-start gap-2 rounded-lg border border-destructive/40 bg-destructive/10 px-3 py-2.5 text-sm text-destructive">
                    <AlertCircle className="w-4 h-4 mt-0.5 shrink-0" />
                    <span>{error}</span>
                  </div>
                )}

                {success && (
                  <div className="flex items-center gap-2 rounded-lg border border-green-500/40 bg-green-500/10 px-3 py-2.5 text-sm text-green-400">
                    <Check className="w-4 h-4 shrink-0" />
                    <span>Setup type updated.</span>
                  </div>
                )}

                <button
                  onClick={handleReassign}
                  disabled={selectedTradeId === "" || reassignMutation.isPending}
                  className="flex items-center gap-1.5 rounded-lg bg-primary px-3 py-1.5 text-sm font-semibold text-primary-foreground transition hover:bg-primary/90 active:scale-[0.98] disabled:opacity-50 disabled:cursor-not-allowed"
                >
                  {reassignMutation.isPending ? (
                    <Loader2 className="w-3.5 h-3.5 animate-spin" />
                  ) : (
                    <Tag className="w-3.5 h-3.5" />
                  )}
                  Update
                </button>
              </>
            )}
          </>
        )}
      </div>
    </div>
  );
}

function AdminPanel() {
  const queryClient = useQueryClient();
  const [revealed, setRevealed] = useState<RevealedCode | null>(null);
  const [error, setError] = useState<string | null>(null);

  const usersQuery = useQuery({ queryKey: ADMIN_USERS_KEY, queryFn: listAdminUsers });

  const createMutation = useMutation({
    mutationFn: createAdminUser,
    onSuccess: (user: AdminUser & { code: string }) => {
      setError(null);
      setRevealed({ userId: user.id, code: user.code, isNew: true });
      queryClient.invalidateQueries({ queryKey: ADMIN_USERS_KEY });
    },
    onError: (err) => setError(err instanceof Error ? err.message : "Failed to create user."),
  });

  const revokeMutation = useMutation({
    mutationFn: revokeAdminUser,
    onSuccess: (result) => {
      setError(null);
      setRevealed({ userId: result.id, code: result.code, isNew: false });
    },
    onError: (err) => setError(err instanceof Error ? err.message : "Failed to revoke access code."),
  });

  async function handleLogout() {
    await adminLogout();
    queryClient.setQueryData(ADMIN_SESSION_KEY, false);
  }

  return (
    <div className="min-h-[100dvh] bg-background text-foreground font-sans px-4 py-10">
      <div className="max-w-2xl mx-auto">
        <div className="flex items-center justify-between mb-8">
          <div className="flex items-center gap-2.5">
            <div className="w-9 h-9 rounded-lg bg-primary/20 flex items-center justify-center border border-primary/30">
              <ShieldCheck className="w-4.5 h-4.5 text-primary" />
            </div>
            <span className="font-semibold tracking-tight text-xl">Admin</span>
          </div>
          <button
            onClick={handleLogout}
            className="flex items-center gap-1.5 text-sm text-muted-foreground hover:text-foreground transition"
          >
            <LogOut className="w-4 h-4" />
            Sign out
          </button>
        </div>

        {revealed && <CodeReveal revealed={revealed} onDismiss={() => setRevealed(null)} />}

        {error && (
          <div className="flex items-start gap-2 rounded-lg border border-destructive/40 bg-destructive/10 px-3 py-2.5 text-sm text-destructive mb-4">
            <AlertCircle className="w-4 h-4 mt-0.5 shrink-0" />
            <span>{error}</span>
          </div>
        )}

        <div className="rounded-2xl border border-border/50 bg-card/60 backdrop-blur-xl p-6 shadow-2xl">
          <div className="flex items-center justify-between mb-5">
            <h2 className="text-base font-semibold tracking-tight">Users</h2>
            <button
              onClick={() => createMutation.mutate()}
              disabled={createMutation.isPending}
              className="flex items-center gap-1.5 rounded-lg bg-primary px-3 py-1.5 text-sm font-semibold text-primary-foreground transition hover:bg-primary/90 active:scale-[0.98] disabled:opacity-50"
            >
              {createMutation.isPending ? (
                <Loader2 className="w-3.5 h-3.5 animate-spin" />
              ) : (
                <Plus className="w-3.5 h-3.5" />
              )}
              New user
            </button>
          </div>

          {usersQuery.isLoading && <p className="text-sm text-muted-foreground">Loading…</p>}
          {usersQuery.isError && <p className="text-sm text-destructive">Failed to load users.</p>}

          {usersQuery.data && usersQuery.data.length === 0 && (
            <p className="text-sm text-muted-foreground">No users yet.</p>
          )}

          <div className="space-y-2">
            {usersQuery.data?.map((user) => (
              <div
                key={user.id}
                className="flex items-center justify-between rounded-lg border border-border/50 bg-background/40 px-4 py-3"
              >
                <div>
                  <p className="text-sm font-medium">
                    User {user.id}{user.nickname ? ` (${user.nickname})` : ""}
                  </p>
                  <p className="text-xs text-muted-foreground">
                    Created {new Date(user.createdAt).toLocaleDateString()}
                  </p>
                  <div className="flex items-center gap-3 mt-1">
                    <span className="text-xs text-muted-foreground">
                      {user.weekCount} {user.weekCount === 1 ? "week" : "weeks"}
                    </span>
                    <span className="text-xs text-muted-foreground">·</span>
                    <span className="text-xs text-muted-foreground">
                      {user.tradeCount} {user.tradeCount === 1 ? "trade" : "trades"}
                    </span>
                    {user.lastActivity && (
                      <>
                        <span className="text-xs text-muted-foreground">·</span>
                        <span className="text-xs text-muted-foreground">
                          active {formatRelativeTime(user.lastActivity)}
                        </span>
                      </>
                    )}
                  </div>
                </div>
                <button
                  onClick={() => revokeMutation.mutate(user.id)}
                  disabled={revokeMutation.isPending}
                  className="text-sm rounded-lg border border-border/60 px-3 py-1.5 hover:bg-accent transition disabled:opacity-50"
                >
                  Revoke &amp; reissue
                </button>
              </div>
            ))}
          </div>
        </div>

        <EditAboutPanel />
        <LoginEventsPanel />
        <SetupTypeChangeLogPanel />
        <SetupTypeReassignPanel users={usersQuery.data ?? []} />
      </div>
    </div>
  );
}

export function AdminPage() {
  const sessionQuery = useQuery({ queryKey: ADMIN_SESSION_KEY, queryFn: getAdminSession });

  if (sessionQuery.isLoading) return null;
  if (!sessionQuery.data) return <AdminLoginForm />;
  return <AdminPanel />;
}
